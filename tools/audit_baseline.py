"""Compare two fresh native trials with the published baseline and write audit evidence."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from sweep import DEFAULT_FRACTIONS, default_ranges


ROOT = Path(__file__).resolve().parents[1]


def read(path: Path):
    return json.loads(path.read_text())


def comparable(row: dict) -> dict:
    """Drop machine-specific file locations, retaining every numerical result."""
    return {key: value for key, value in row.items()
            if key not in {"source_files", "solver_provenance"} and
            key != "mesh"} | {
                "mesh": {key: value for key, value in row["mesh"].items()
                         if key != "geometry_file"}
            }


def audit(first: Path, second: Path, published: Path) -> dict:
    a, b = (read(path / "data/dataset.json") for path in (first, second))
    reference = read(published / "run_manifest.json")
    failures = read(published / "data/failures.json")
    config = read(ROOT / "config/reference_design.json")
    fresh_hz = read(first / "baseline_fem.json")["flexible_frequencies_hz"]
    published_hz = reference["baseline_flexible_frequencies_hz"]
    difference = [100 * abs(new - old) / old for new, old in zip(fresh_hz, published_hz)]
    if len(fresh_hz) != len(published_hz):
        raise ValueError("baseline mode count changed")
    rows_equal = [comparable(x) == comparable(y)
                  for x, y in zip(a["records"], b["records"])]
    if len(a["records"]) != len(b["records"]):
        rows_equal = [False]
    failure_equal = [
        {"design_id": row["design_id"], "inputs": row["inputs"], "error": row["error"]}
        for row in read(first / "data/failures.json")
    ] == [
        {"design_id": row["design_id"], "inputs": row["inputs"], "error": row["error"]}
        for row in read(second / "data/failures.json")
    ]
    ranges = default_ranges(config)
    units = {key: ("kg" if key.endswith("_kg") else
                   "Pa" if key.endswith("_Pa") else
                   "kg/m^3" if key == "rho_kg_m3" else "m")
             for key in ranges}
    return {
        "source": "calculix_ccx_native",
        "published_manifest": str((published / "run_manifest.json").resolve().relative_to(ROOT)),
        "trial_directories": [str(path.resolve().relative_to(ROOT)) for path in (first, second)],
        "published_frequencies_hz": published_hz,
        "fresh_frequencies_hz": fresh_hz,
        "difference_percent_by_mode": difference,
        "difference_exceeds_0_1_percent": [x > 0.1 for x in difference],
        "trial_successes": [len(a["records"]), len(b["records"])],
        "trial_failures": [len(read(first / "data/failures.json")),
                           len(read(second / "data/failures.json"))],
        "trial_rows_identical": all(rows_equal),
        "trial_failures_identical": failure_equal,
        "published_successes": len(read(published / "data/dataset.json")["records"]),
        "published_rejections": len(failures),
        "rejection_reason_counts": {
            "ambiguous_mode_tracking": sum(
                row["error"].startswith("ambiguous mode tracking:") for row in failures),
            "other": sum(
                not row["error"].startswith("ambiguous mode tracking:") for row in failures),
        },
        "published_target_count": read(published / "data/dataset.json")["metadata"]["target_count"],
        "published_raw_flexible_count": len(
            read(published / "data/dataset.json")["records"][0]["raw_flexible_frequencies_hz"]),
        "published_mesh_size_m": read(published / "data/dataset.json")["metadata"]["mesh_size_m"],
        "sweep_ranges": {key: {"minimum": lo, "maximum": hi, "unit": units[key],
                               "baseline_fraction": list(DEFAULT_FRACTIONS[key])}
                         for key, (lo, hi) in ranges.items()},
        "physical_test_performed": False,
    }


def markdown(result: dict) -> str:
    rows = ["| Mode | Published (Hz) | Fresh (Hz) | Difference (%) |",
            "| ---: | ---: | ---: | ---: |"]
    for i, (old, new, delta) in enumerate(zip(result["published_frequencies_hz"],
                                               result["fresh_frequencies_hz"],
                                               result["difference_percent_by_mode"]), 1):
        rows.append(f"| {i} | {old:.6f} | {new:.6f} | {delta:.6f} |")
    ranges = ["| Input | Minimum | Maximum | Unit |",
              "| --- | ---: | ---: | --- |"]
    for key, value in result["sweep_ranges"].items():
        ranges.append(f"| `{key}` | {value['minimum']:.8g} | {value['maximum']:.8g} | {value['unit']} |")
    return "\n".join([
        "# Phase 1 audit findings", "",
        "Generated by `tools/audit_baseline.py` from two new native trials and the",
        "committed reference data. Numerical evidence is in",
        "`results/audit/baseline_reproduction.json`. No physical test was performed.", "",
        "## Reproduction", "", *rows, "",
        f"Difference above 0.1%: **{any(result['difference_exceeds_0_1_percent'])}**.",
        f"Trial successes: **{result['trial_successes']}**; trial failures: **{result['trial_failures']}**.",
        f"Accepted rows identical after excluding file locations: **{result['trial_rows_identical']}**.",
        f"Rejected rows identical: **{result['trial_failures_identical']}**.", "",
        "## Sampling and targets", "",
        "The sweep uses seeded Latin hypercube sampling, with one independently",
        "permuted stratum per input. The baseline is included separately. Failed",
        "candidates are replaced from additional seeded batches.", "",
        *ranges, "",
        f"The published run contains **{result['published_successes']}** accepted designs",
        f"and **{result['published_rejections']}** rejected candidates. All",
        f"**{result['rejection_reason_counts']['ambiguous_mode_tracking']}** recorded",
        "rejections have the `ambiguous mode tracking` error; the stored error",
        "only gives the minimum MAC, so the responsible mode is not recoverable",
        "from that file alone.", "",
        f"The published dataset stores **{result['published_raw_flexible_count']}** raw",
        f"flexible frequencies per case but trains on **{result['published_target_count']}**",
        "targets. Its third target is the mean of the third/fourth near-degenerate",
        "pair. The Campbell screen evaluates those targets only; higher raw modes",
        "are absent from that screen.", "",
        "## Mesh and hub", "",
        f"The published sweep metadata specifies a fixed **{result['published_mesh_size_m']:.4g} m**",
        "target mesh size for every case. The separate baseline refinement uses",
        "half that target size. Arm nodes inside the hub square are tied by",
        "three translational `*EQUATION` constraints to bilinear interpolation",
        "of the four hub-corner displacements. The equivalent hub thickness is",
        "`sqrt(t_plate^2 + 12*((gap+t_plate)/2)^2)`; density and elastic moduli",
        "are scaled by `2*t_plate/t_equivalent` to match the idealized pair's",
        "areal mass, membrane stiffness, and bending stiffness.", "",
        "## Deviations from the plan's assumptions", "",
        "The current code already uses MAC on motor-tip displacements, has an",
        "out-of-range surrogate guard, and samples by Latin hypercube. The",
        "tracking implementation handles one specific degenerate pair rather",
        "than general clusters. See `docs/plan_deviations.md`.", "",
    ]) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--first", type=Path, default=ROOT / "build/audit_trial_a")
    parser.add_argument("--second", type=Path, default=ROOT / "build/audit_trial_b")
    parser.add_argument("--published", type=Path, default=ROOT / "results/calculix_full500")
    args = parser.parse_args()
    result = audit(args.first, args.second, args.published)
    output = ROOT / "results/audit/baseline_reproduction.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, indent=2) + "\n")
    (ROOT / "docs/audit_findings.md").write_text(markdown(result))
    print(json.dumps({"output": str(output), "identical": result["trial_rows_identical"],
                      "max_difference_percent": max(result["difference_percent_by_mode"])}, indent=2))


if __name__ == "__main__":
    main()
